import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const contractRoot = join(here, "../contracts/v0_9");
const contractRootV1 = join(here, "../contracts/v1_0");
const readJson = (name) => JSON.parse(readFileSync(join(contractRoot, name), "utf8"));
const basic = readJson("catalog-v0_9-basic.json");
const common = readJson("common-types-v0_9.json");
const extensions = readJson("extension-schemas.json");
const legacy = readJson("legacy-custom-component-schemas.json");
const manifest = readJson("registry-manifest.json");
// The 1.0 checks: the plugin's own catalog (a2ui_core/catalogs/hermes-v1_0.json, generated by scripts/generate_express.py) and the SDK's common types.
const catalogV1 = JSON.parse(readFileSync(join(here, "../../a2ui_core/catalogs/hermes-v1_0.json"), "utf8"));
const commonV1 = JSON.parse(readFileSync(join(contractRootV1, "common-types-v1_0.json"), "utf8"));

const ajv = new Ajv2020({
  allErrors: false,
  strict: false,
  strictSchema: false,
  validateFormats: false,
  discriminator: true,
  unevaluated: true,
  code: { source: true, esm: true, optimize: 2 },
});
ajv.addSchema(common);
ajv.addSchema(basic, basic.$id);
ajv.addSchema({ ...basic, $id: "https://a2ui.org/specification/v0_9/catalog.json" }, "https://a2ui.org/specification/v0_9/catalog.json");

const names = [...manifest.basicEnabled, ...Object.keys(legacy), ...Object.keys(extensions)];
const validatorRefs = Object.create(null);
for (const name of names) {
  const id = `https://a2ui-hermes.invalid/v0_9/components/${name}.json`;
  const schema = basic.components[name]
    ? { $id: id, $ref: `${basic.$id}#/components/${name}` }
    : { ...combineCustom(name, legacy[name] ?? extensions[name]), $id: id };
  if (!schema) throw new Error(`Missing local schema for ${name}`);
  ajv.addSchema(schema, id);
  validatorRefs[name] = id;
}

// 1.0. A function call is refused before any schema runs, so the common types' FunctionCall (which points at a second catalog document)
// is cut out here exactly as the Python validator cuts it out. The exports are prefixed V1_.
commonV1.$defs.FunctionCall = { not: {} };
// The spec's extension keys are Unicode identifiers (\p{XID_Start}), which Python's re cannot read; both validators keep to ASCII, and the
// whole key must match (here `$` is the end of the string; a2ui_core/validate.py writes it `\Z`, because Python's `$` lets a trailing newline through).
commonV1.$defs.Extensions = { type: "object", propertyNames: { pattern: "^[A-Za-z_][A-Za-z0-9_]*$" } };
absoluteRefs(catalogV1, commonV1.$id);
ajv.addSchema(commonV1, commonV1.$id);
ajv.addSchema(catalogV1, catalogV1.$id);
const namesV1 = Object.keys(catalogV1.components);
for (const name of namesV1) {
  const id = `https://a2ui-hermes.invalid/v1_0/components/${name}.json`;
  ajv.addSchema({
    $id: id,
    allOf: [{ $ref: `${commonV1.$id}#/$defs/ComponentCommon` }, { $ref: `${catalogV1.$id}#/components/${name}` }],
    unevaluatedProperties: false,
  }, id);
  validatorRefs[`V1_${name}`] = id;
}

const output = standaloneCode(ajv, validatorRefs);
const modulePath = join(here, "validators.generated.js");
const declarationPath = join(here, "validators.generated.d.ts");
writeFileSync(modulePath, `${output.trimEnd()}\n`, "utf8");
const exported = [...names, ...namesV1.map((name) => `V1_${name}`)];
writeFileSync(
  declarationPath,
  `import type { ValidateFunction } from "ajv";\n${exported.map((name) => `export const ${name}: ValidateFunction;`).join("\n")}\n`,
  "utf8",
);
process.stdout.write(`Generated ${exported.length} standalone local validators at ${modulePath}\n`);

function absoluteRefs(node, base) {
  if (Array.isArray(node)) {
    for (const child of node) absoluteRefs(child, base);
  } else if (node && typeof node === "object") {
    if (typeof node.$ref === "string" && node.$ref.startsWith("common_types.json#")) {
      node.$ref = base + node.$ref.slice("common_types.json".length);
    }
    for (const child of Object.values(node)) absoluteRefs(child, base);
  }
}

function combineCustom(name, sourceSchema) {
  if (!sourceSchema || typeof sourceSchema !== "object") return undefined;
  return {
    type: "object",
    properties: {
      id: { type: "string", minLength: 1, maxLength: 128 },
      component: { const: name },
      accessibility: { $ref: "https://a2ui.org/specification/v0_9/common_types.json#/$defs/AccessibilityAttributes" },
      weight: { type: "number" },
      ...sourceSchema.properties,
    },
    required: ["id", "component", ...(sourceSchema.required ?? [])],
    additionalProperties: false,
  };
}
