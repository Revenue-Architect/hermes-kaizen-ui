// Image source policy for generated UI (Image, ImageBlock, ImageGallery, ImageText, ImageTextLarge,
// OptionCard/ListItem images). Pure functions so they can be unit tested and reused by the element policy.
//
// Allowed:   https:, http: (including LAN hosts), data:image/* up to 2 MB, and a local image path, which
//            the plugin's tool copied into the saved view (see `renderMedia`).
// Rejected:  javascript:, file:, blob:, ftp:, vbscript:, data: of any non-image type, URLs carrying
//            credentials, protocol-relative URLs and relative paths.
export const MAX_DATA_IMAGE_BYTES = 2 * 1024 * 1024;
export const MAX_IMAGE_SRC_LENGTH = Math.ceil(MAX_DATA_IMAGE_BYTES * 4 / 3) + 256;

export type ImageDecision =
  | { kind: 'url'; src: string }
  | { kind: 'media'; path: string }
  | { kind: 'reject'; reason: string };

const IMAGE_MIME = /^image\/(?:png|jpe?g|gif|webp|avif|bmp|svg\+xml|x-icon|vnd\.microsoft\.icon)$/i;
const IMAGE_EXT = /\.(?:png|jpe?g|webp|gif|bmp|avif|svg)$/i;
const CONTROL = /[\u0000-\u001f\u007f]/;

function dataImageBytes(src: string): number | null {
  const match = /^data:([^;,]*)((?:;[^;,]*)*),([\s\S]*)$/i.exec(src);
  if (!match) return null;
  const mime = match[1].trim();
  if (!IMAGE_MIME.test(mime)) return null;
  const base64 = /;base64$/i.test(match[2]);
  const payload = match[3];
  if (base64) {
    if (!/^[A-Za-z0-9+/_-]*={0,2}$/.test(payload)) return null;
    return Math.floor((payload.length * 3) / 4) - (payload.endsWith('==') ? 2 : payload.endsWith('=') ? 1 : 0);
  }
  try { return new TextEncoder().encode(decodeURIComponent(payload)).length; } catch { return null; }
}

export function classifyImageSrc(raw: unknown): ImageDecision {
  if (typeof raw !== 'string') return { kind: 'reject', reason: 'not-a-string' };
  const src = raw.trim();
  if (!src) return { kind: 'reject', reason: 'empty' };
  if (src.length > MAX_IMAGE_SRC_LENGTH) return { kind: 'reject', reason: 'too-large' };
  // Browsers strip control characters inside a scheme (`java\tscript:`); never pass them on.
  if (CONTROL.test(src.slice(0, 64))) return { kind: 'reject', reason: 'control-characters' };
  if (/^data:/i.test(src)) {
    const bytes = dataImageBytes(src);
    if (bytes === null) return { kind: 'reject', reason: 'data-not-image' };
    if (bytes > MAX_DATA_IMAGE_BYTES) return { kind: 'reject', reason: 'data-too-large' };
    return { kind: 'url', src };
  }
  if (/^https?:\/\//i.test(src)) {
    try {
      const url = new URL(src);
      if (url.protocol !== 'http:' && url.protocol !== 'https:') return { kind: 'reject', reason: 'scheme' };
      if (!url.hostname) return { kind: 'reject', reason: 'no-host' };
      if (url.username || url.password) return { kind: 'reject', reason: 'credentials-in-url' };
      return { kind: 'url', src: url.href };
    } catch { return { kind: 'reject', reason: 'invalid-url' }; }
  }
  const media = src.replace(/^MEDIA:\s*/i, '');
  const hasScheme = /^[a-z][a-z0-9+.-]*:/i.test(media) && !/^[a-z]:[\\/]/i.test(media);
  if (!hasScheme && !media.startsWith('//') && !media.startsWith('\\\\') && IMAGE_EXT.test(media)
      && (media.startsWith('/') || media.startsWith('~') || /^[a-z]:[\\/]/i.test(media) || /^MEDIA:/i.test(src))) {
    return { kind: 'media', path: media };
  }
  return { kind: 'reject', reason: 'scheme' };
}

/** CSS url() values that appear in inline styles generated by the library. */
export function cssUrls(value: string): string[] {
  const out: string[] = [];
  for (const m of value.matchAll(/url\(\s*(?:"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'|([^)]*))\s*\)/gi)) out.push((m[1] ?? m[2] ?? m[3] ?? '').replace(/\\([0-9a-f]{1,6}\s?|.)/gi, (_, c: string) => /^[0-9a-f]+\s?$/i.test(c) ? String.fromCodePoint(parseInt(c, 16)) : c));
  return out;
}

/** True only when every url() in a CSS value is an allowed network/data image (media paths cannot be backgrounds). */
export function safeCssImageValue(value: unknown): boolean {
  if (typeof value !== 'string' || !/url\(/i.test(value)) return true;
  const urls = cssUrls(value);
  return urls.length > 0 && urls.every((u) => classifyImageSrc(u).kind === 'url');
}
